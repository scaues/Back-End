<?php

$n1 = 104;
$n2 = 15;
$operacao= "*";

if ($operacao == "+"){
    echo "a soma", $n1+ $n2;
}
elseif($operacao == "-"){
    echo "a subtração", $n1- $n2;
}
elseif($operacao == "*"){
    echo "a multiplicação", $n1* $n2;
}
elseif($operacao == "/"){
    echo "a divisão", $n1 / $n2;
}
?>